"""Branch-explicit, bounded argument transformations of harmonic polylogarithms."""

from functools import lru_cache

import sympy as s

from .errors import UnsupportedExpressionError
from .hpl_algebra import integrate_from_zero, shuffle_words
from .hpl_endpoints import hpl_at_one
from .hpl_reduce import _extract
from .symbolic import HPL


def _validate(word, z, domain):
    if domain != "0<z<1":
        raise UnsupportedExpressionError("Explicit domain='0<z<1' is required")
    if not isinstance(z, s.Symbol):
        raise TypeError("The argument must be a SymPy Symbol")
    checked = HPL(word, z)
    word = tuple(map(int, checked.word))
    if len(word) > 24:
        raise UnsupportedExpressionError("Transformation weight exceeds 24")
    return word


def _h(word, z):
    return HPL(word, z) if word else s.S.One


def negate_hpl(word, z, *, domain=None):
    """Express H_word(-z) at positive z on the upper principal-cut boundary.

    Trailing zeroes are first extracted with shuffle algebra. Their explicit
    logarithms acquire +i*pi; origin-analytic factors use letter reversal.
    """
    word = _validate(word, z, domain)
    if not word:
        return s.S.One
    if all(a == 0 for a in word):
        return (s.log(z) + s.I * s.pi) ** len(word) / s.factorial(len(word))
    if word[-1] == 0:
        expanded = _extract(word, z, False, True)
        return expanded.xreplace(
            {atom: negate_hpl(atom.word, z, domain=domain) for atom in expanded.atoms(HPL)}
        )
    return (-1) ** sum(a != 0 for a in word) * _h(tuple(-a for a in word), z)


@lru_cache(maxsize=256)
def _reflect(word, z):
    if not word:
        return s.S.One
    if all(a == 1 for a in word):
        return (-s.log(z)) ** len(word) / s.factorial(len(word))
    if word[0] == 1:
        # Shuffle H_1 H_tail. Every other word has fewer leading ones,
        # so recursion strictly decreases the leading-one count at this weight.
        counts = shuffle_words((1,), word[1:])
        multiplicity = counts.pop(word)
        return s.expand(
            (
                -s.log(z) * _reflect(word[1:], z)
                - sum(count * _reflect(other, z) for other, count in counts.items())
            )
            / multiplicity
        )
    endpoint = hpl_at_one(word)
    return endpoint - integrate_from_zero(_reflect(word[1:], z) / (1 - z), z)


def reflect_hpl(word, z, *, domain=None):
    """Express H_word(1-z) at z for binary words of weight at most eight.

    The explicit real interval excludes all branch ambiguities. Endpoint constants retain exact MZV objects where unreduced. The extra
    letter generated by -1 is not guessed.
    """
    word = _validate(word, z, domain)
    if len(word) > 8 or any(a not in (0, 1) for a in word):
        raise UnsupportedExpressionError("Reflection supports binary words through weight eight")
    return _reflect(word, z)
